export function translate(text, language = 'en', values = {}) {
  if (typeof text !== 'string') return '';
  let result = language === 'zh' ? messages[text] || text : text;
  if (language === 'zh' && !messages[text]) {
    // The API returns readable English errors; interpolate its variable messages too.
    for (const [pattern, translated] of Object.entries(messages)) {
      if (!pattern.includes('{')) continue;
      const keys = [...pattern.matchAll(/\{(\w+)\}/g)].map(m => m[1]);
      const regex = pattern.replace(/[.*+?^${}()|[\]\\]/g, '\\$&').replace(/\\\{\w+\\\}/g, '(.+?)');
      const match = text.match(new RegExp(`^${regex}$`));
      if (match) { result = translated; values = Object.fromEntries(keys.map((key, i) => [key, match[i + 1]])); break; }
    }
  }
  return result.replace(/\{(\w+)\}/g, (match, key) => values[key] ?? match);
}

let language = 'en';
try { language = localStorage.getItem('slidelink-language') === 'zh' ? 'zh' : 'en'; } catch {}
export const locale = () => language === 'zh' ? 'zh-CN' : 'en-US';
export const t = (text, values) => translate(text, language, values);
export function applyLanguage(root = document) {
  document.documentElement.lang = language === 'zh' ? 'zh-CN' : 'en';
  root.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  for (const attr of ['placeholder', 'aria-label', 'title']) {
    root.querySelectorAll(`[data-i18n-${attr}]`).forEach(el => el.setAttribute(attr, t(el.getAttribute(`data-i18n-${attr}`))));
  }
  root.querySelectorAll('[data-language]').forEach(el => { el.value = language; });
}
export function setLanguage(value) {
  language = value === 'zh' ? 'zh' : 'en';
  try { localStorage.setItem('slidelink-language', language); } catch {}
  applyLanguage();
  document.dispatchEvent(new Event('languagechange'));
}
export function initLanguage() {
  applyLanguage();
  document.querySelectorAll('[data-language]').forEach(el => el.addEventListener('change', () => setLanguage(el.value)));
  window.addEventListener('storage', e => { if (e.key === 'slidelink-language') setLanguage(e.newValue); });
}
